const COUNTRY_CODES = new Set(COUNTRIES.map((country) => country.code))

// Strict by design: the select always submits an exact code, so anything else
// reaching this is free text and must be rejected rather than coerced.
export function isValidCountryCode(code: string): boolean {
  return COUNTRY_CODES.has(code)
}
